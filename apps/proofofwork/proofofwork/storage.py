"""Photo validation and storage.

Uploads are decoded with Pillow, re-encoded as JPEG (which strips EXIF/GPS
metadata and any embedded payload) and saved under a random name in a
directory that is never served statically. Original filenames are discarded.
"""
import io
import os
import re
import secrets
import time
import warnings

from flask import current_app
from PIL import Image, ImageOps, UnidentifiedImageError

ALLOWED_EXTENSIONS = {"jpg", "jpeg", "png", "webp"}
ALLOWED_FORMATS = {"JPEG", "PNG", "WEBP"}
STORED_NAME_RE = re.compile(r"^[0-9a-f]{32}\.jpg$")
MAX_DIMENSION = 2400
Image.MAX_IMAGE_PIXELS = 50_000_000


class UploadError(ValueError):
    pass


def _human_size(num_bytes):
    if num_bytes >= 1024 * 1024:
        return f"{num_bytes / (1024 * 1024):g} MB"
    return f"{num_bytes // 1024} KB"


def stored_path(stored_name):
    """Resolve a stored file name to a path, rejecting anything not generated by us."""
    if not isinstance(stored_name, str) or not STORED_NAME_RE.match(stored_name):
        raise ValueError("invalid stored file name")
    return os.path.join(current_app.config["UPLOAD_DIR"], stored_name)


def save_image_bytes(data, original_filename):
    ext = original_filename.rsplit(".", 1)[-1].lower() if "." in original_filename else ""
    if ext not in ALLOWED_EXTENSIONS:
        raise UploadError("Only JPEG, PNG or WebP photos are accepted.")
    if not data:
        raise UploadError("The selected file is empty.")
    max_bytes = current_app.config["MAX_PHOTO_BYTES"]
    if len(data) > max_bytes:
        raise UploadError(f"Photos must be {_human_size(max_bytes)} or smaller.")

    try:
        with warnings.catch_warnings():
            warnings.simplefilter("error", Image.DecompressionBombWarning)
            with Image.open(io.BytesIO(data)) as probe:
                fmt = probe.format
                probe.verify()
            if fmt not in ALLOWED_FORMATS:
                raise UploadError("Only JPEG, PNG or WebP photos are accepted.")
            img = Image.open(io.BytesIO(data))
            img.load()
    except UploadError:
        raise
    except (UnidentifiedImageError, OSError, SyntaxError, ValueError, EOFError,
            Image.DecompressionBombError, Image.DecompressionBombWarning):
        raise UploadError("The file could not be read as an image.") from None

    try:
        img = ImageOps.exif_transpose(img)
    except Exception:  # malformed EXIF: keep the pixels, drop the orientation hint
        pass
    if img.mode in ("RGBA", "LA") or (img.mode == "P" and "transparency" in img.info):
        rgba = img.convert("RGBA")
        img = Image.new("RGB", rgba.size, (255, 255, 255))
        img.paste(rgba, mask=rgba.getchannel("A"))
    elif img.mode != "RGB":
        img = img.convert("RGB")
    img.thumbnail((MAX_DIMENSION, MAX_DIMENSION))

    out = io.BytesIO()
    img.save(out, "JPEG", quality=85, optimize=True)
    payload = out.getvalue()

    stored_name = secrets.token_hex(16) + ".jpg"
    try:
        with open(stored_path(stored_name), "xb") as fh:
            fh.write(payload)
    except OSError:
        # Details (including the server path) go to the server log only.
        current_app.logger.exception("Could not write uploaded photo")
        raise UploadError("The photo could not be saved on the server. Please try again later.") from None
    return {"stored_name": stored_name, "width": img.width, "height": img.height, "byte_size": len(payload)}


def save_upload(file_storage):
    if file_storage is None or not file_storage.filename:
        raise UploadError("Choose a photo to upload.")
    data = file_storage.stream.read(current_app.config["MAX_PHOTO_BYTES"] + 1)
    return save_image_bytes(data, file_storage.filename)


def delete_stored(stored_name):
    try:
        os.remove(stored_path(stored_name))
    except (FileNotFoundError, ValueError):
        pass


def list_stored_files():
    """Names of files in the upload dir that match our generated naming scheme."""
    folder = current_app.config["UPLOAD_DIR"]
    if not os.path.isdir(folder):
        return []
    return [name for name in os.listdir(folder) if STORED_NAME_RE.match(name)]


def file_exists(stored_name):
    try:
        return os.path.isfile(stored_path(stored_name))
    except ValueError:
        return False


def file_age_seconds(stored_name):
    return time.time() - os.path.getmtime(stored_path(stored_name))


def purge_all_stored():
    """Delete every file in the upload dir that matches our generated naming scheme."""
    for name in list_stored_files():
        delete_stored(name)
